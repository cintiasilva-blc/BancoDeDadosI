
/* 
Criar uma tabela chamada categoria -> CREATE TABLE nome 

id_categoria deve ser a chave primária, gerado automaticamente e do tipo BIGINT -> BIGINT GENERATED BY DEFAULT AS IDENTITY primary key

nome deve ser do tipo varchar e ser obrigatório -> varchar(x) e not null, respectivamente.
*/
create table categoria (
  id_categoria bigint generated by default as identity primary key,
  nome varchar(100) not null
);