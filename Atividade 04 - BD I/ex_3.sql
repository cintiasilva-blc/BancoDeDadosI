create table produto (
    id_produto bigint generated by default as identity primary key,
    nome varchar(100) not null, 
    preco numeric(10,2) not null check (preco >= 0), 
    estoque integer not null default 0 check (estoque >= 0),
    id_categoria bigint not null,
    foreign key (id_categoria) references categoria(id_categoria)
);

/*
numeric() é um tipo e define a quantidade max. de digitos e as casas decimais

check () valida uma condição
 
integer é um tipo e armazena inteiros

default 0; default define um valor padrão, defalt 0 define o valor padão como zero, se fizermos o cadastro de um produto sem informar o estoque

foregein key e references criam o relacionamento entre as tabelas
  neste exercicio: a coluna id_categoria da tabela produto faz referencia a uma categoria que já existe na tabela categoria

*/